# Collects every theme's image credits (themes/<id>/credits.json) into
# credits-data.js, so the Customize panel can list them. (A script file rather
# than fetching the JSON, because fetch() is blocked on file:// pages.)
# Run from the repo root: python tools/gen-credits.py
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
credits = {}
for f in sorted((root / 'themes').glob('*/credits.json')):
    credits[f.parent.name] = json.loads(f.read_text(encoding='utf-8'))

out = root / 'credits-data.js'
with open(out, 'w', encoding='utf-8') as o:
    o.write('// Generated by tools/gen-credits.py from themes/*/credits.json. Don\'t edit by hand.\n')
    o.write('window.THEME_CREDITS = ')
    json.dump(credits, o, ensure_ascii=False, indent=1)
    o.write(';\n')
print(', '.join(f'{k}: {len(v)}' for k, v in credits.items()))
